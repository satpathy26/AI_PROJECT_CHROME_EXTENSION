const API_KEY = "YOUR_API_KEY";


async function solveMCQ(question) {
    if (!question?.trim()) {
        return "Please provide a question.";
    }

    if (!API_KEY || API_KEY === "YOUR_GROQ_API_KEY") {
        return "Please configure your Groq API key.";
    }

    try {
        
        const response = await fetch(
            "https://api.groq.com/openai/v1/chat/completions",
            {
                method: "POST",
                headers: {
                    "Content-Type": "application/json",
                    "Authorization": `Bearer ${API_KEY}`
                },
                body: JSON.stringify({
                    model: "openai/gpt-oss-120b",
                    messages: [
                        {
                            role: "system",
                            content: `You are an expert MCQ solver.

Choose the single correct option from the provided choices.

Return ONLY valid JSON in exactly this format:
{
  "answer": "D",
  "explanation": "Brief explanation of why D is correct."
}

The answer must identify the correct option letter.
The explanation must be 2-3 sentences.
Do not include markdown or text outside the JSON.`
                        },
                        {
                            role: "user",
                            content: question
                        }
                    ],
                    temperature: 0.2,
                    max_tokens: 300
                })
            }
        );

        if (!response.ok) {
            const errorText = await response.text();

            console.error(
                "Groq API error:",
                response.status,
                errorText
            );

            if (response.status === 429) {
                return "Groq rate limit exceeded. Please check your Groq usage and limits, then try again later.";
            }

            if (
                response.status === 401 ||
                response.status === 403
            ) {
                return "Groq authentication failed. Check your API key and account access.";
            }

            if (response.status === 400) {
                return "Invalid Groq request. Check the model name and request parameters.";
            }

            return `Groq API error (${response.status}). Check the console for details.`;
        }

        const data = await response.json();

        const result =
            data.choices?.[0]?.message?.content;

        if (!result) {
            return "No answer generated by the AI.";
        }

        const cleaned = result
            .replace(/```json/gi, "")
            .replace(/```/g, "")
            .trim();

        const parsed = JSON.parse(cleaned);

        if (!parsed.answer || !parsed.explanation) {
            return "The AI returned an incomplete answer. Please try again.";
        }

        return `Answer: ${parsed.answer}\n\nExplanation:\n${parsed.explanation}`;

    } catch (error) {
        console.error("MCQ Error:", error);

        return "Unable to contact Groq or process its response. Check your connection and console.";
    }
}

export { solveMCQ };